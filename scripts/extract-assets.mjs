// Pulls every unique base64 image out of legacy/index.html (plus the loose legacy
// files), writes AVIF + WebP to public/img, and emits a typed manifest with
// intrinsic sizes so components can always set width/height.
import { mkdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import sharp from "sharp";

const OUT = "public/img";
const MAX_W = 1600;

// Order of first appearance in legacy/index.html.
const EMBEDDED = [
  "portrait-1",
  "portrait-2",
  "portrait-3",
  "startup-solution-logo",
  "cert-rangpur-divisional-contest",
  "cert-baust-intra-university-contest",
  "cert-10-minute-school-web-design",
  "cert-uy-lab-video-editing",
  "cert-cybertech-freelancing",
  "cert-global-space-leadership",
];
const LOOSE = {
  "gallery-1": "legacy/ahmed1.png",
  "gallery-2": "legacy/ahmed2.png",
  "gallery-3": "legacy/ahmed3.png",
  "gallery-4": "legacy/ahmed4.png",
  "gallery-5": "legacy/ahmed5.png",
  header: "legacy/ahmedheader.jpeg",
};

mkdirSync(OUT, { recursive: true });
const html = readFileSync("legacy/index.html", "utf8");
const seen = new Set();
const sources = [];
for (const m of html.matchAll(/data:image\/[a-z+]+;base64,([A-Za-z0-9+/=]+)/g)) {
  const buf = Buffer.from(m[1], "base64");
  const hash = createHash("sha1").update(buf).digest("hex");
  if (seen.has(hash)) continue;
  seen.add(hash);
  sources.push(buf);
}
if (sources.length !== EMBEDDED.length) {
  throw new Error(`Expected ${EMBEDDED.length} unique embedded images, found ${sources.length}`);
}

const jobs = [
  ...sources.map((buf, i) => [EMBEDDED[i], buf]),
  ...Object.entries(LOOSE).map(([name, path]) => [name, readFileSync(path)]),
];

// Variants derived from the images above.
const NAVY = [13, 27, 42];
const byName = Object.fromEntries(jobs);
const derived = [];
// The agency logo is drawn in white/grey for dark backgrounds. The dark version keeps its
// shape and tonal hierarchy (white parts solid, grey parts lighter) but in navy, for the
// cream sections.
{
  const { data, info } = await sharp(byName["startup-solution-logo"]).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += 4) {
    const lum = (data[i] + data[i + 1] + data[i + 2]) / 765;
    data[i + 3] = Math.round(data[i + 3] * (0.55 + 0.45 * lum)); // grey parts stay distinct but read clearly on cream
    [data[i], data[i + 1], data[i + 2]] = NAVY;
  }
  derived.push(["startup-solution-logo-dark", await sharp(data, { raw: info }).png().toBuffer()]);
}
// Small certificate previews for the credits list (the viewer uses the full size).
const THUMB_W = 480;
for (const [name, buf] of jobs.filter(([n]) => n.startsWith("cert-"))) {
  derived.push([`${name}-thumb`, await sharp(buf).resize({ width: THUMB_W, withoutEnlargement: true }).toBuffer()]);
}
jobs.push(...derived);

const manifest = {};
let total = 0;
for (const [name, buf] of jobs) {
  const base = sharp(buf).rotate().resize({ width: MAX_W, withoutEnlargement: true });
  const { width, height } = await base.clone().toBuffer({ resolveWithObject: true }).then((r) => r.info);
  await base.clone().avif({ quality: 55, effort: 6 }).toFile(`${OUT}/${name}.avif`);
  await base.clone().webp({ quality: 78, effort: 6 }).toFile(`${OUT}/${name}.webp`);
  const avif = statSync(`${OUT}/${name}.avif`).size;
  const webp = statSync(`${OUT}/${name}.webp`).size;
  total += avif;
  manifest[name] = { avif: `/img/${name}.avif`, webp: `/img/${name}.webp`, width, height };
  console.log(name.padEnd(40), `${width}x${height}`, `avif ${(avif / 1024).toFixed(0)}KB`, `webp ${(webp / 1024).toFixed(0)}KB`);
}

const names = Object.keys(manifest).map((n) => JSON.stringify(n)).join(" | ");
writeFileSync(
  "src/content/assets.generated.ts",
  `// Generated by scripts/extract-assets.mjs — do not edit.
export type AssetName = ${names};
export type Asset = { avif: string; webp: string; width: number; height: number };
export const assets: Record<AssetName, Asset> = ${JSON.stringify(manifest, null, 2)};
`,
);
console.log(`\nAVIF total: ${(total / 1024).toFixed(0)}KB across ${jobs.length} images`);
